"""Render bench/README.md from bench/results/*.json. Deterministic: same inputs, same bytes.

python -m gridcase.bench.readme [--results bench/results] [--out bench/README.md]
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from gridcase.bench.run import SuiteResult
from gridcase.bench.score import score
from gridcase.config import ROOT


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.0f}%"


def _num(x: float | None, fmt: str = "{:.3f}") -> str:
    return "–" if x is None else fmt.format(x)


def render(runs: list[tuple[str, SuiteResult, dict[str, Any]]]) -> str:
    lines = [
        "# GridCase benchmark",
        "",
        "Root-cause accuracy of the investigation engine on replayed real events and on",
        "fault-injected synthetic cases, with the false-alarm rate on clean windows. Generated by",
        "`python -m gridcase.bench.readme` from `bench/results/*.json`; do not edit by hand.",
        "",
        "Synthetic cases are generated from the same hypothesis templates the system tests, so",
        "their score partly measures self-agreement; the replay cases are the independent signal.",
        "Historical replays see revised EIA data and no price data (see docs/DECISIONS.md).",
        "",
        "## Leaderboard",
        "",
        "| run | model | validator | replay top-1 | synthetic top-1 | top-3 | Brier "
        "| false alarms | cost/case | latency/case |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, r, s in runs:
        syn, rep, nul = s["synthetic"], s["replay"], s["null"]
        validator = "on" if r.config.get("validator", True) else "off"
        cells = [
            name,
            str(r.config.get("model")),
            validator,
            f"{_pct(rep['top1'])} ({rep['n']})",
            f"{_pct(syn['top1'])} ({syn['n']})",
            _pct(syn["top3"]),
            _num(syn["brier"]),
            f"{_pct(nul['false_alarm_rate'])} ({nul['n']})",
            f"${_num(syn['cost_usd_per_case'], '{:.4f}')}",
            f"{_num(syn['latency_s_per_case'], '{:.1f}')} s",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    if runs:
        name, r, s = runs[-1]
        syn = s["synthetic"]
        lines += [
            "",
            f"## Per hypothesis ({name})",
            "",
            "| generator | n | top-1 | top-3 |",
            "|---|---|---|---|",
        ]
        for h, v in syn["per_hypothesis"].items():
            lines.append(f"| {h} | {v['n']} | {_pct(v['top1'])} | {_pct(v['top3'])} |")
        lines += [
            "",
            f"## Per region ({name})",
            "",
            "| region | n | top-1 | top-3 |",
            "|---|---|---|---|",
        ]
        for reg, v in syn["per_region"].items():
            lines.append(f"| {reg} | {v['n']} | {_pct(v['top1'])} | {_pct(v['top3'])} |")
        hyps = sorted({*syn["confusion"], *(p for row in syn["confusion"].values() for p in row)})
        if hyps:
            lines += [
                "",
                f"## Confusion matrix ({name}; rows = truth, columns = predicted top)",
                "",
            ]
            lines.append("| truth \\ predicted | " + " | ".join(hyps) + " |")
            lines.append("|---|" + "---|" * len(hyps))
            for t in sorted(syn["confusion"]):
                row = syn["confusion"][t]
                lines.append(f"| {t} | " + " | ".join(str(row.get(p, 0)) for p in hyps) + " |")
        traj = syn["trajectory"]
        if traj:
            lines += ["", f"## Trajectory ({name})", ""]
            lines.append(f"- H0 tested first: {_pct(traj['h0_first_rate'])}")
            lines.append(f"- ≥ 2 hypotheses tested: {_pct(traj['two_plus_hypotheses_rate'])}")
            lines.append(
                f"- mean steps run: {_num(traj['mean_steps'], '{:.1f}')}; mean skipped "
                f"(already refuted): {_num(traj['mean_skipped'], '{:.1f}')}"
            )
            lines.append(f"- mean LLM calls per case: {_num(traj['mean_llm_calls'], '{:.1f}')}")
        rep = s["replay"]
        if r.replay:
            lines += [
                "",
                f"## Replay cases ({name})",
                "",
                "| case | entity | truth | predicted top | top-1 | recheck |",
                "|---|---|---|---|---|---|",
            ]
            for c in r.replay:
                pred = c.predicted[0] if c.predicted else ("error: " + (c.error or "")[:40])
                truth = c.ground_truth[0] if c.ground_truth else "–"
                cells = [
                    c.scenario_id,
                    c.entity,
                    truth,
                    pred,
                    "✓" if c.top1 else "✗",
                    str(c.recheck or "–"),
                ]
                lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def render_readme(results_dir: Path, out: Path) -> str:
    runs: list[tuple[str, SuiteResult, dict[str, Any]]] = []
    for p in sorted(results_dir.glob("*.json")):
        r = SuiteResult.model_validate_json(p.read_text())
        runs.append((p.stem, r, score(r)))
    text = render(runs)
    out.write_text(text)
    return text


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(ROOT / "bench" / "results"))
    ap.add_argument("--out", default=str(ROOT / "bench" / "README.md"))
    a = ap.parse_args()
    render_readme(Path(a.results), Path(a.out))


if __name__ == "__main__":
    main()
